// Deterministic seeded RNG for scene layout (mulberry32).
// Scenes lay out trees/stones/relays with this instead of Math.random() so
// placement is stable across server/client renders and repeatable in tests.
export function mulberry32(seed) {
  let a = seed >>> 0;
  return function () {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
