// lib/earth4/species-regions.js
// EARTH 4 — WHERE SPECIES LIVE (Nov 14, 2026 —
// ~/workspace/earth4/build-species-regions.py).
//
// One entry per catalogue species: the biogeographic realms it may
// spawn in, and where that came from. `regions: []` means
// UNRESTRICTED — the dataset holds nothing usable for that species,
// so it spawns anywhere, exactly as before. No species is ever
// silently given a region it doesn't have.
//
// Sources: 'listed' = the dataset's own `realms` column (all values,
// not just the first); 'inferred-from-distribution' = the dataset's
// `distribution_areas` text entries, place names mapped to realms by
// ordered keyword rules (most specific first; an ambiguous token maps
// to EVERY realm it plausibly touches, so the mapping never wrongly
// excludes a species from where it lives). mrgid: references are
// Marine Regions Gazetteer IDs with no gazetteer in the workspace,
// so they resolve to nothing; `habitat` carries biome names, not
// regions, so it gives no inference either.
//
// THE BOXES ARE CRUDE. Each realm is a small list of lat/lon
// bounding boxes, loosely drawn around the continents (standard WWF
// terrestrial realms). A box edge is not a real range boundary, and
// where two boxes overlap both realms claim the ground — that is
// the transition zone, and it is intended. The boxes exist to stop
// the obvious wrongness (a tropical marine worm in Redwater,
// Alberta), not to draw precise ranges. A species that truly lives
// on both sides of a box edge will read wrong at the edge; that is
// the known limit of this dataset, stated here, not hidden.
//
// The spawner (lib/earth4/spawner.js) tests the cell's lat/lon
// against these boxes: a species spawns only where its regions
// allow, or anywhere when unrestricted. The environment rule still
// applies on top (land/water).
//
