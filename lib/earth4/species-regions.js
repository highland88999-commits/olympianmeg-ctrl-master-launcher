/** The region entry for a species name, or null when unknown. */
export function regionsFor(name) {
  return REGIONS_FOR_SPECIES[name] || null;
}

/**
 * True when a species may spawn at a lat/lon: unrestricted species
 * (regions []) may spawn anywhere; a restricted species only where
 * one of its realms' boxes holds the point. Pure and total — an
 * unknown name is treated as unrestricted, never as an error.
 */
export function speciesRegionsAllow(name, lat, lon) {
  const entry = REGIONS_FOR_SPECIES[name];
  if (!entry || !entry.regions.length) return true;
  for (const realm of entry.regions) {
    const boxes = REGION_BOXES[realm];
    if (!boxes) continue;
    for (const b of boxes) {
      if (lat >= b.latMin && lat <= b.latMax
        && lon >= b.lonMin && lon <= b.lonMax) return true;
    }
  }
  return false;
}
