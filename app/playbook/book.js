export function pageCount() {
  return PAGES.length;
}

export function clampPage(i) {
  if (i < 0) return 0;
  if (i >= PAGES.length) return PAGES.length - 1;
  return i;
}

// fraction of the book read, for the progress bar
export function progressOf(i) {
  return (clampPage(i) + 1) / PAGES.length;
}

export function nextPage(i) {
  return clampPage(i + 1);
}

export function prevPage(i) {
  return clampPage(i - 1);
}
