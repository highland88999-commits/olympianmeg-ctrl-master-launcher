// scripts/build-vortex-manifest.mjs
// Regenerates lib/vortex/wraps-manifest.js — the full list of ecosystem
// graphics the vortex tube draws its skins from (Merlin, 2026-10-29:
// "use all graphics that live in our ecosystem").
// Run: node scripts/build-vortex-manifest.mjs
import { readdirSync, statSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, extname, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(fileURLToPath(import.meta.url), '..', '..');
const PUBLIC = join(ROOT, 'public');
const OUT_DIR = join(ROOT, 'lib', 'vortex');
const OUT = join(OUT_DIR, 'wraps-manifest.js');
const IMAGE_EXTS = new Set(['.webp', '.png', '.jpg', '.jpeg', '.svg']);

function walk(dir, out) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) { walk(p, out); continue; }
    if (!IMAGE_EXTS.has(extname(name).toLowerCase())) continue;
    out.push('/' + relative(PUBLIC, p).split(sep).join('/'));
  }
  return out;
}

const files = walk(PUBLIC, []).sort();
mkdirSync(OUT_DIR, { recursive: true });
writeFileSync(
  OUT,
  '// GENERATED by scripts/build-vortex-manifest.mjs — do not hand-edit.\n' +
  `// ${files.length} ecosystem graphics (Merlin, 2026-10-29: every image\n` +
  '// in public/ is a candidate vortex skin). Re-run the script after\n' +
  '// adding or removing images.\n' +
  `export const VORTEX_WRAP_FILES = ${JSON.stringify(files, null, 2)};\n` +
  `export const VORTEX_WRAP_COUNT = ${files.length};\n`
);
console.log(`wrote ${OUT} with ${files.length} files`);
